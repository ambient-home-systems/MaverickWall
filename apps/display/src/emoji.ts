/**
 * One emoji as an `<img>`, or `null` for a key with no artwork.
 *
 * An `<img>` rather than an inline SVG: the artwork is somebody else's
 * drawing (Twemoji, CC-BY 4.0 — see `apps/server/assets/emoji/LICENSES.md`),
 * where the closed glyph set is ours and inlines as a path. Same-origin,
 * `img-src 'self'` already permits it, and nothing here runs a script.
 *
 * `null` rather than an empty node is `glyphNode`'s rule: the caller decides,
 * and every caller decides the same way — draw nothing rather than a box with
 * no picture in it.
 */
export function emojiNode(key: unknown, className = ''): HTMLImageElement | null {
  if (!isEmojiKey(key)) return null;
  const img = document.createElement('img');
  img.src = `/assets/emoji/${key}.svg`;
  img.alt = LABELS[key];
  if (className !== '') img.className = className;
  return img;
}
