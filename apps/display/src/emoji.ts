/**
 * The wall's bundled emoji artwork (D6, plan item P4.2).
 *
 * The image ships no emoji font, so an emoji set as *text* is a third-party
 * asset resolved on the device — a tablet draws its vendor's cartoon, the
 * tablet beside it draws a different vendor's, and some kiosks draw an empty
 * box. `no-emoji.test.ts` used to ban emoji everywhere a screen renders for
 * exactly that reason; D6 (2026-09-24) narrows the ban to the e-paper
 * renderer, because the image ships a curated Twemoji set under
 * `apps/server/assets/emoji/` instead — the same picture on every browser
 * wall, same-origin, served from `/assets/emoji/<key>.svg`.
 *
 * What travels through a widget's config and this module's own API is a
 * **key**, never a code point: `EMOJI_KEYS` is the whole vocabulary a designed
 * style may draw from, the way `GLYPH_KEYS` is for the closed icon set. A key
 * a bundle does not recognise draws nothing, the `glyphNode` rule, rather than
 * a broken image or the raw string.
 *
 * `apps/server/src/emoji.ts` transcribes the two blocks below character for
 * character — `emoji-parity.test.ts` compares them as text, the seam
 * `glyph-parity.test.ts` already sits at, for the reason it sits there: two
 * copies of one vocabulary is this project's most repeated bug.
 *
 * Text a household typed itself — a countdown's own title — renders in the
 * device's own font (Q9) and is untouched by this module: it is their string,
 * and the wall does not rewrite it.
 */

