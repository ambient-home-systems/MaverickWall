/**
 * A 12x16 bitmap face, drawn for e-paper (RFC 006 phase 11).
 *
 * The 8x8 face beside this one is the only alphabet the panel has ever had,
 * and a bigger panel got bigger type by *multiplying* it: 8, 16, 24, 32. Two
 * things follow from that and both are faults. The rungs are eight pixels
 * apart, so a 3.7x range of panels collapses onto four sizes and the role that
 * carries a month cell's event names lands on **the same 16px on a 10.3" panel
 * and a 13.3" one** — measured at each panel's own read distance, 12.6 and 9.9
 * arc-minutes, so the larger, further panel draws it *smaller*. And a doubled
 * 8x8 is a photographic enlargement of a square: it says nothing more than the
 * 8x8 did, only larger, at 18px of advance where a face drawn at 12x16 needs
 * 13.
 *
 * **This is the brand mark's argument, one alphabet along.** `lit-cell-small.svg`
 * is a five-column *redraw* rather than the seven-column mark scaled down,
 * because below about 20px a seven-column field stops being a grid and becomes
 * grey texture with a dot in it. A glyph is the same: what carries at 16px is a
 * shape drawn on a 12x16 grid, not a shape drawn on an 8x8 one with every pixel
 * doubled.
 *
 * ## What is drawn, and why it is drawn this way
 *
 * Every pixel is on or off by design. There is no antialiasing anywhere in this
 * file and there cannot be one on the panel — a half-lit pixel on e-paper is a
 * grey smear that survives until the next full refresh, which is the rule
 * `epaper/metrics.ts` already states for a row boundary.
 *
 * **Vertical stems are 2px and horizontals 1px**, which is the shipped 8x8's own
 * colour at twice the size: that face has 1px strokes in an 8px box, and 2px in
 * a 16px box is the same fraction. Stated as a rule because it is the one thing
 * a redraw could quietly lose — a lighter face would read as *thinner* on every
 * panel that adopts this rung, and nothing in a test would say so. Measured at
 * the panels these rungs are used on, a stroke subtends about 1.2 arc-minutes
 * at the reader's eye on all three e-ink sizes, which is the same stroke the
 * 8x8 draws today.
 *
 * ## The grid
 *
 *     cols   0..10 carry ink; col 11 is always clear
 *     rows   0..13    caps and ascenders (14 rows)
 *            4..13    x-height (10 rows)
 *            14..15   descenders (2 rows)
 *
 * **Those are the shipped 8x8's own proportions, doubled, and that is the
 * point.** font8x8 puts a 7-row cap and a 1-row descender in an 8-row box, so
 * 87.5% of its cell is cap; the first draft of this face put an 11-row cap in a
 * 16-row box, which is 69%, and the consequence was measured before it shipped:
 * at the same 16px line box a household's event titles would have been drawn
 * **21% shorter** than the 8x8 draws them today. A face that says more per line
 * and less per letter is not the trade this phase is for. 14 rows of cap and 2
 * of descender is the 8x8's ratio exactly, so what the new faces buy is the
 * width and only the width.
 *
 * **Column 11 is clear on every glyph and a test says so.** The grade
 * (`font.ts`) is a one-pixel horizontal dilation, so ink in the last column
 * would leave the cell — and a cell that grows is a metric change, which is a
 * reflow, which is what forecloses partial refresh.
 */

