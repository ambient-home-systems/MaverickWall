/**
 * A 16x24 bitmap face, drawn for e-paper (RFC 006 phase 11).
 *
 * The sibling of `font-12x16.ts`, and its docstring is the argument for both:
 * one 8x8 face at integer scales is four sizes across a 3.7x range of panels,
 * and a doubled square is a photographic enlargement rather than a bigger
 * alphabet. This is the rung a 10.3" panel draws its body at and a 13.3" panel
 * draws its month-cell names at — 24 pixels of glyph at **17 pixels of
 * advance**, against the 27 the 8x8 needs to reach the same height. Same
 * height, 37% narrower, which is the whole payoff: a panel that says more
 * rather than one that says the same thing bigger.
 *
 * ## Drawn, not scaled
 *
 * Every pixel is on or off by design and nothing here is antialiased — a
 * half-lit pixel on e-paper is a grey smear that survives until the next full
 * refresh. **Vertical stems are 3px and horizontals 2px**, which holds the
 * shipped 8x8's stem-to-height ratio at three times the size (1px in an 8px
 * box, 3px in a 24px one), so no panel that adopts this rung draws lighter
 * type than it draws today. That is the one property a redraw could quietly
 * lose and nothing would say so.
 *
 * ## The grid
 *
 *     cols   0..14 carry ink; col 15 is always clear
 *     rows   0..20    caps and ascenders (21 rows)
 *            6..20    x-height (15 rows)
 *            21..23   descenders (3 rows)
 *
 * **Those are the shipped 8x8's own proportions, tripled**, and the reason is
 * written up in `font-12x16.ts`: a face that reaches the same line box with a
 * shorter cap draws a household's event titles *smaller* than the face it
 * replaces, whatever it buys in width. 21 rows of cap and 3 of descender in a
 * 24-row cell is 87.5%, which is font8x8's ratio exactly.
 *
 * Column 15 is clear on every glyph and a test says so: the grade (`font.ts`)
 * is a one-pixel horizontal dilation, so ink in the last column would leave the
 * cell, and a cell that grows is a metric change — which is a reflow, which is
 * what forecloses partial refresh.
 */

