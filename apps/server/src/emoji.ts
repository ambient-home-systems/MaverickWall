/**
 * The emoji vocabulary, server-side (D6, plan item P4.2).
 *
 * A module or a catalogue entry names an emoji by **key**, never a code
 * point, so what reaches the manifest and the admin is the same key both
 * renderers agree on. The artwork itself is a curated Twemoji subset under
 * `apps/server/assets/emoji/`, served from `/assets/emoji/<key>.svg` by
 * `http/static.ts` — same-origin, immutably cached, and rule three holds:
 * nothing here fetches anything at runtime.
 *
 * **The two blocks below are transcribed from `apps/display/src/emoji.ts`
 * character for character** and `emoji-parity.test.ts` compares them as text,
 * the seam `glyph-parity.test.ts` already sits at. The display bundle has no
 * bundler and cannot import this file, and a server test cannot import *from*
 * it — two copies of one vocabulary is this project's most repeated bug, and
 * the cure each time is to hold the copies to each other rather than to trust
 * that they agree.
 *
 * `no-emoji.test.ts` no longer scans this file or its consumers: D6
 * (2026-09-24) permits emoji on a browser wall, drawn from this vocabulary as
 * bundled artwork. It still scans `epaper/**` — an e-paper panel draws no
 * emoji, drawn or otherwise, and never will until it has its own 1-bit motifs.
 */

