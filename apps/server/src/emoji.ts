/**
 * One emoji as an `<img>`, or `''` for a key with no artwork.
 *
 * For the server-rendered admin — the store card today, a designed wall style
 * tomorrow reads this same vocabulary through `emojiNode` instead, because the
 * display bundle builds a node rather than a string (it has no `innerHTML`
 * anywhere). The key is checked against the vocabulary before it is used, so
 * nothing a stranger's catalogue entry named reaches this string unvalidated.
 */
export function emojiImg(key: unknown, className: string): string {
  if (!isEmojiKey(key)) return '';
  return `<img class="${className}" src="/assets/emoji/${key}.svg" alt="${LABELS[key]}">`;
}
